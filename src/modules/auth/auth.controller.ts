import { AuthProfileResultDto } from './dto/get-profile.dto';
import { TraceNode } from '@erixcel/traceflow';
import { AuthAcceptInvitationResultDto } from './dto/accept-invitation.dto';
import { InvitationPreviewDto } from './dto/invitation.dto';
import { Controller, Post, Body, Get, UseGuards, Request, Query, Header } from '@nestjs/common';
import { ApiTags, ApiOperation, ApiResponse, ApiBearerAuth } from '@nestjs/swagger';
import { HttpErrorDto } from '@dto/http-error.dto';
import { AuthService } from './auth.service';
import { LoginDto } from '@modules/auth/dto/login.dto';
import { LoginResponseDto } from '@modules/auth/dto/login.dto';
import { RegisterDto } from '@modules/auth/dto/register.dto';
import { GoogleAuthUrlDto } from '@modules/auth/dto/google-url.dto';
import { GoogleAuthUrlResponseDto } from '@modules/auth/dto/google-url.dto';
import { GoogleCallbackQueryDto } from '@modules/auth/dto/google-callback.dto';
import { JwtAuthGuard } from '@modules/auth/guards/jwt-auth.guard';
import { ForgotPasswordDto } from '@modules/auth/dto/forgot-password.dto';
import { ResetPasswordDto } from '@modules/auth/dto/reset-password.dto';
import { MessageResponseDto } from '@modules/auth/dto/forgot-password.dto';
import type { AuthenticatedRequest } from '@modules/auth/types/authenticated-user.type';
import { InvitationTokenDto } from '@modules/admin/modules/pyme/dto/find-all.dto';

@ApiTags('auth')
@Controller('auth')
export class AuthController {
  constructor(private readonly authService: AuthService) {}

  @Post('login')
  @ApiOperation({ summary: 'User login' })
  @ApiResponse({ status: 200, type: LoginResponseDto })
  @ApiResponse({ status: 400, type: HttpErrorDto })
  @TraceNode({ name: 'login', type: 'controller' })
  async login(@Body() loginDto: LoginDto) {
    return this.authService.login(loginDto);
  }

  @Post('register')
  @ApiOperation({ summary: 'Register a new PYME or consultant user' })
  @ApiResponse({ status: 200, type: LoginResponseDto })
  @ApiResponse({ status: 400, type: HttpErrorDto })
  @TraceNode({ name: 'register', type: 'controller' })
  async register(@Body() registerDto: RegisterDto) {
    return this.authService.register(registerDto);
  }

  @Get('invitation')
  @ApiOperation({ summary: 'Validate a PYME invitation token' })
  @ApiResponse({ status: 200, type: InvitationPreviewDto })
  @ApiResponse({ status: 400, type: HttpErrorDto })
  @TraceNode({ name: 'invitation', type: 'controller' })
  invitation(@Query() query: InvitationTokenDto) {
    return this.authService.getInvitationPreview(query.token);
  }

  @Post('invitation/accept')
  @UseGuards(JwtAuthGuard)
  @ApiBearerAuth()
  @ApiOperation({ summary: 'Accept a PYME invitation with the current account' })
  @ApiResponse({ status: 200, type: AuthAcceptInvitationResultDto })
  @ApiResponse({ status: 400, type: HttpErrorDto })
  @TraceNode({ name: 'acceptInvitation', type: 'controller' })
  acceptInvitation(@Request() req: AuthenticatedRequest, @Body() body: InvitationTokenDto) {
    return this.authService.acceptInvitation(req.user, body.token);
  }

  @Get('google/url')
  @ApiOperation({ summary: 'Get Google OAuth URL generated by backend' })
  @ApiResponse({ status: 200, type: GoogleAuthUrlResponseDto })
  @ApiResponse({ status: 400, type: HttpErrorDto })
  @TraceNode({ name: 'googleUrl', type: 'controller' })
  googleUrl(@Query() query: GoogleAuthUrlDto) {
    return this.authService.getGoogleAuthUrl(query);
  }

  @Get('google/callback')
  @Header('Content-Type', 'text/html')
  @ApiOperation({ summary: 'Google OAuth callback for popup login' })
  @ApiResponse({ status: 200, description: 'HTML response that posts the session to the opener window' })
  @ApiResponse({ status: 400, type: HttpErrorDto })
  @TraceNode({ name: 'googleCallback', type: 'controller' })
  googleCallback(@Query() query: GoogleCallbackQueryDto) {
    return this.authService.handleGoogleCallback(query);
  }

  @Get('profile')
  @UseGuards(JwtAuthGuard)
  @ApiBearerAuth()
  @ApiOperation({ summary: 'Get current user profile' })
  @ApiResponse({ status: 200, type: AuthProfileResultDto, description: 'Returns current user information' })
  @ApiResponse({ status: 400, type: HttpErrorDto })
  @TraceNode({ name: 'getProfile', type: 'controller' })
  getProfile(@Request() req: AuthenticatedRequest) {
    return this.authService.getProfile(req.user);
  }

  @Post('forgot-password')
  @ApiOperation({ summary: 'Request password reset link via email' })
  @ApiResponse({ status: 200, type: MessageResponseDto })
  @ApiResponse({ status: 400, type: HttpErrorDto })
  @TraceNode({ name: 'forgotPassword', type: 'controller' })
  async forgotPassword(@Body() forgotPasswordDto: ForgotPasswordDto) {
    return this.authService.forgotPassword(forgotPasswordDto);
  }

  @Post('reset-password')
  @ApiOperation({ summary: 'Reset user password using token' })
  @ApiResponse({ status: 200, type: MessageResponseDto })
  @ApiResponse({ status: 400, type: HttpErrorDto })
  @TraceNode({ name: 'resetPassword', type: 'controller' })
  async resetPassword(@Body() resetPasswordDto: ResetPasswordDto) {
    return this.authService.resetPassword(resetPasswordDto);
  }
}
